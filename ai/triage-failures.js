'use strict';
// AI-augmented failure triage (advisory only).
// Reads the parity summary, sends ONLY the failing/flaky scenarios (names, statuses in both suites,
// truncated error messages — no secrets, no page content) to Claude, and asks for a structured verdict
// per failure. The answer is rendered as Markdown for the PR comment and the job summary.
// Guardrails: the AI never changes the gate verdict, output is schema-validated, the step is
// skipped when ANTHROPIC_API_KEY is absent (forks, local runs), and any API error is non-blocking.
const fs = require('fs');

const CATEGORIES = ['PRODUCT_BUG', 'TEST_BUG', 'MIGRATION_GAP', 'FLAKY', 'ENVIRONMENT', 'TEST_DATA'];
const MAX_FAILURES = 15;

function collectFailures(summary) {
  const statusOf = (suite, key) => (summary.matrix || []).find(m => m.key === key)?.[suite] || 'missing';
  const items = [];
  for (const suite of ['cypress', 'playwright']) {
    const metrics = summary[suite] || {};
    for (const f of metrics.failing || []) items.push({ suite, kind: 'failed', key: `${f.feature} › ${f.scenario}`, error: f.error || '' });
    for (const f of metrics.flaky_scenarios || []) items.push({ suite, kind: 'flaky', key: `${f.feature} › ${f.scenario}`, error: '' });
  }
  return items.slice(0, MAX_FAILURES).map((item, index) => ({
    id: index + 1,
    ...item,
    cypress_status: statusOf('cypress', item.key),
    playwright_status: statusOf('playwright', item.key),
  }));
}

function buildPrompt(failures) {
  return [
    'You are a senior SDET triaging CI failures during a Cypress -> Playwright migration.',
    'Both suites run the SAME Gherkin scenarios against the same public demo site (automationexercise.com).',
    'Cross-suite signal: failing in BOTH suites usually points to the application, the environment or test data;',
    'failing ONLY in Playwright usually points to a migration gap in the step definitions; flaky means it passed on retry or across repeats.',
    '',
    `Classify each failure into exactly one category: ${CATEGORIES.join(', ')}.`,
    'Answer with ONLY a JSON array, no prose, one object per failure:',
    '[{"id": <number>, "category": "<CATEGORY>", "confidence": "low|medium|high", "evidence": "<max 25 words>", "next_action": "<max 25 words>"}]',
    'Never invent facts that are not in the input. If unsure, use confidence "low".',
    '',
    'Failures:',
    JSON.stringify(failures, null, 2),
  ].join('\n');
}

function parseTriage(text, failures) {
  const match = String(text).match(/\[[\s\S]*\]/);
  if (!match) throw new Error('No JSON array in model answer');
  const ids = new Set(failures.map(f => f.id));
  return JSON.parse(match[0])
    .filter(v => v && ids.has(v.id) && CATEGORIES.includes(v.category))
    .map(v => ({
      id: v.id,
      category: v.category,
      confidence: ['low', 'medium', 'high'].includes(v.confidence) ? v.confidence : 'low',
      evidence: String(v.evidence || '').slice(0, 300),
      next_action: String(v.next_action || '').slice(0, 300),
    }));
}

function toMarkdown(failures, verdicts, model) {
  const cell = s => String(s || '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
  const lines = ['', `### 🤖 AI failure triage (advisory · ${model})`, '', '| # | Suite | Scenario | Cypress / Playwright | Category | Confidence | Evidence | Next action |', '|---:|---|---|---|---|---|---|---|'];
  for (const f of failures) {
    const v = verdicts.find(x => x.id === f.id);
    lines.push(`| ${f.id} | ${f.suite} | ${cell(f.key)} | ${f.cypress_status} / ${f.playwright_status} | ${v ? `**${v.category}**` : '—'} | ${v ? v.confidence : '—'} | ${cell(v?.evidence)} | ${cell(v?.next_action)} |`);
  }
  lines.push('', '_Generated by an LLM from test names and error messages only. It does not affect the gate — a human decides._');
  return lines.join('\n') + '\n';
}

async function callClaude(prompt, model, apiKey) {
  const response = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-api-key': apiKey, 'anthropic-version': '2023-06-01' },
    body: JSON.stringify({ model, max_tokens: 2000, temperature: 0, messages: [{ role: 'user', content: prompt }] }),
    signal: AbortSignal.timeout(60_000),
  });
  if (!response.ok) throw new Error(`Anthropic API HTTP ${response.status}: ${(await response.text()).slice(0, 200)}`);
  const body = await response.json();
  return (body.content || []).filter(b => b.type === 'text').map(b => b.text).join('\n');
}

async function main() {
  const summaryFile = process.env.SUMMARY_FILE || 'comparison-summary.json';
  const output = process.env.TRIAGE_FILE || 'triage.md';
  const model = process.env.TRIAGE_MODEL || 'claude-sonnet-5-5';
  if (!fs.existsSync(summaryFile)) { console.log(`${summaryFile} not found; nothing to triage.`); return; }
  const failures = collectFailures(JSON.parse(fs.readFileSync(summaryFile, 'utf8')));
  if (failures.length === 0) { console.log('No failing or flaky scenarios; AI triage skipped.'); return; }
  if (!process.env.ANTHROPIC_API_KEY) {
    fs.writeFileSync(output, '\n_AI triage skipped: ANTHROPIC_API_KEY is not configured for this run._\n');
    console.log('ANTHROPIC_API_KEY not configured; AI triage skipped.');
    return;
  }
  const answer = await callClaude(buildPrompt(failures), model, process.env.ANTHROPIC_API_KEY);
  const verdicts = parseTriage(answer, failures);
  const markdown = toMarkdown(failures, verdicts, model);
  fs.writeFileSync(output, markdown);
  fs.writeFileSync(process.env.TRIAGE_JSON || 'triage.json', JSON.stringify({ model, failures, verdicts }, null, 2));
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, markdown);
  console.log(`AI triage: ${verdicts.length}/${failures.length} failures classified.`);
}

if (require.main === module) main().catch(error => { console.log(`::warning title=AI triage::${error.message}`); });
module.exports = { collectFailures, buildPrompt, parseTriage, toMarkdown, CATEGORIES };
